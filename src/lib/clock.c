#include <time.h>

#include "pnut_internal.h"

/****************************************************************************
 * Public Functions
 ****************************************************************************/

/****************************************************************************
 * Name: pnut_now
 *
 * Description:
 *   The monotonic clock, in milliseconds.
 *
 ****************************************************************************/

uint64_t pnut_now(void)
{
  struct timespec ts;

  clock_gettime(CLOCK_MONOTONIC, &ts);
  return (uint64_t)ts.tv_sec * 1000 + (uint64_t)ts.tv_nsec / 1000000;
}
